package io.opentelemetry.instrumentation.spring.cloud.gateway.common.internal;

import java.util.regex.Pattern;
import javax.annotation.Nullable;

/**
 * This class is internal and is hence not for public use. Its APIs are unstable and can change at
 * any time.
 */
public final class GatewayRouteIdConverger {
  private static final String INVALID_RANDOM_ROUTE_ID =
      "org.springframework.util.AlternativeJdkIdGenerator@";
  private static final Pattern UUID_PATTERN =
      Pattern.compile(
          "^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$");

  /**
   * Returns the route ID unless it is empty or was randomly generated by Spring Cloud Gateway.
   *
   * @param routeId the route ID
   * @return the route ID to record, or {@code null} when it should be ignored
   */
  @Nullable
  public static String converge(@Nullable String routeId) {
    if (routeId == null || routeId.isEmpty()) {
      return null;
    }
    if (UUID_PATTERN.matcher(routeId).matches()) {
      return null;
    }
    if (routeId.startsWith(INVALID_RANDOM_ROUTE_ID)) {
      return null;
    }
    return routeId;
  }

  private GatewayRouteIdConverger() {}
}
